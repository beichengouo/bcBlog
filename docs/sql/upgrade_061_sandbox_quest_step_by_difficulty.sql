-- ============================================================
-- 061 委托单步进度上限「按难度分档」+ 配置化
--
-- 背景（实测）：单步上限原本是一个全局数字（默认 40，后来被管理员调成 55），一视同仁地卡所有委托。
--   难度 1 的杂活（「清点并保养后勤库房武器」）本该一步做完，却被卡在 55%：
--   AI 那一步的 quest_progress 写的是 100、叙述里也写着「完成并领到了报酬」，
--   服务端却因为上限只把进度记到 55% —— 于是「剧情说完成、状态说没完成」，
--   而且那段"领到了报酬"还一直挂在进度说明里（委托奖励其实一分没发）。
--
-- 现在改成按难度分档（管理员可在后台「旅人委托板」里改这一串数字）：
--   难度 1 简单 → 100（允许一步做完）
--   难度 2 一般 →  70
--   难度 3 棘手 →  50
--   难度 4 危险 →  35
--   难度 5 凶险 →  20
-- 写几档就按几档算；某一档写坏会用 sandbox_quest_progress_step_max（单值）顶替。
--
-- 同时修掉两处相关问题（代码改动，这里只记录配置）：
--   ① AI 声称完成却被单步上限截断时，不再静默：会写清「推进到 X%、还剩 Y%」，
--      并触发已有的「AI 自检修正」让它把叙述改成"还没做完"；
--   ② 杂活（chore）不再要求「拿到物品」——清点库房/誊抄账本本来就不产出东西，
--      以前它和采集类共用"必须有物品增量"的校验，实际靠 AI 顺手买的面包才勉强过。
--
-- 脚本幂等，可重复执行。
-- ============================================================

SET NAMES utf8mb4;
USE `bc_blog`;

INSERT IGNORE INTO `sys_config` (`config_key`, `config_value`, `remark`) VALUES
    ('sandbox_quest_step_max_by_difficulty', '100,70,50,35,20',
     '委托单步进度上限（%），按难度 1~5 依次对应：难度 1 允许一步做完；留空或用坏某档则退回 sandbox_quest_progress_step_max');

SELECT `config_key`, `config_value` FROM `sys_config`
WHERE `config_key` IN ('sandbox_quest_step_max_by_difficulty', 'sandbox_quest_progress_step_max',
                       'sandbox_quest_selfcheck');
