-- ============================================================
-- 043 沙盒·位置距离化（km）：地图尺度、交通方式、互动距离门槛
--
-- 背景：
--   以前提示词只给角色 x/y 坐标，AI 算不出"多远"，出现过
--   「39 个坐标单位（约 78 km）只花 180 分钟、8 个单位也花 120 分钟」这种自相矛盾；
--   而且同行/好感度只按名字匹配，两个相隔几百公里的角色也能"隔空互动"。
--
-- 本次改动（配置项，全部可在后台「沙盒世界 → 世界与地图 → 运行参数」里改）：
--   1. sandbox_km_map_width   地图宽度（km）：横向 100 单位对应多少公里，默认 200
--      （前台地图容器是 16:9，纵向距离按 9/16 自动折算）
--   2. sandbox_travel_speeds  交通方式与速度，默认「步行:4,骑乘:20,车船:12,飞行:60」
--      既写进提示词让 AI 按距离挑交通方式，也用于服务端算赶路时间下限
--   3. sandbox_social_max_km  允许写进"同行 / 好感度"的最大距离，默认 30 km，0 = 不限制
-- ============================================================

INSERT IGNORE INTO `sys_config` (`config_key`, `config_value`, `remark`) VALUES
    ('sandbox_km_map_width', '200', '地图宽度（km）：横向 100 个坐标单位对应多少公里，纵向按 16:9 折算'),
    ('sandbox_travel_speeds', '步行:4,骑乘:20,车船:12,飞行:60', '交通方式与速度（名称:km/h，逗号分隔）：提示词与赶路时间下限都用它'),
    ('sandbox_social_max_km', '30', '允许同行/涨好感的角色间最大距离（km），0 表示不限制');
