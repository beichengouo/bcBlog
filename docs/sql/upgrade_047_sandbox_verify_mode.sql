-- 047 沙盒输出自查模式（三档，默认「仅可疑时查」）
--
-- 背景：以前自查是个开关（sandbox_verify_enabled），开着就是"每次行动都多跑一次 AI"，
--   但实测它并没挡住问题——因为自查提示词写成了"照抄器"（要求原样保留每个字段），
--   模型连「晨雾森林 of 野浆果」这种错名、以及不合理的大额花费都照抄了回去。
--
-- 现在改成：
--   1. 自查模式三档，后台「世界与地图 → 输出自查」可切换：
--        off        关闭
--        suspicious 仅可疑时查（默认）：命中规则才多花一次调用
--        always     每次都查
--   2. 可疑判定（命中任一即触发自查）：物品名/商品名里混了英文、花费超过单次上限、
--      地点名不在可用地点里、互动对象不是世界里的角色、状态数值越界；
--   3. 自查提示词改成"除必须纠正的点外，其余一个字不许改"，并把检测到的问题点名列出；
--   4. 能规则化解决的（物品名中英混排、花费超上限）由代码直接处理，不再依赖 AI。
-- ============================================================

INSERT IGNORE INTO `sys_config` (`config_key`, `config_value`, `remark`) VALUES
    ('sandbox_verify_mode', 'suspicious', '沙盒输出自查模式：off 关闭 / suspicious 仅可疑时查（默认） / always 每次都查');

-- 说明：旧的开关 sandbox_verify_enabled 仍然保留——
--   代码读取顺序是「先看 sandbox_verify_mode，没有再回退到旧开关（1=每次都查 / 0=关闭），都没有才用默认的仅可疑时查」，
--   所以这条 INSERT 之后，各库都会切换到「仅可疑时查」（后台可随时改）。
