-- 048 沙盒「三段式输出」+ 文风补充
--
-- 背景：用的是公益免费接口（输出 token 不心疼，但调用次数有限），
--   与其在 AI 掉字段/乱写数值之后再补一次调用，不如让它**在同一次回复里**先打草稿、再自审、最后给终稿。
--
-- 现在的行为（代码里已实现）：
--   1. 开启后，行动提示词会要求输出三段：
--        <draft>…</draft>    先想清楚要做什么、涉及哪些字段、收支怎么来的（≤200 字）
--        <review>…</review>  对照清单自检：地点/坐标、间隔与作息、物品来源与纯中文名、
--                            花费是否与买到的东西相称、是否把集市购买重复算进 coins_change、是否与人设/记忆矛盾
--        <final>{…}</final>  修正后的最终 JSON（服务端只认这一段）
--   2. 服务端用"预填充"把 assistant 消息预置成 <draft> 开头，模型只能接着写，几乎不会跑飞；
--      三段式开启时不会要求 response_format=json_object（否则上游会强制纯 JSON，草稿段直接被判违规）
--   3. 解析只取 <final> 里的 JSON；解析彻底失败时前台展示的兜底文本也会**去掉草稿与自审**，
--      前台的行动接口不再返回 AI 原文（raw_response 只给后台排查用）
--   4. sandbox_style_extra：后台可粘贴酒馆预设里的写作基准段落，会拼进行动提示词的【文风补充】
--
-- 只对「角色行动」生效；旅人纪闻生成、集市生成、记忆总结、AI 写文章保持原样。
-- ============================================================

INSERT IGNORE INTO `sys_config` (`config_key`, `config_value`, `remark`) VALUES
    ('sandbox_draft_mode', 'on', '沙盒角色行动三段式输出（草稿→自审→终稿）：on 开启（默认）/ off 关闭'),
    ('sandbox_style_extra', '', '行动提示词的【文风补充】（可粘贴酒馆预设里的写作基准段落，留空不追加）');
