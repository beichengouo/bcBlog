-- ============================================================
-- 052 沙盒互动收敛：一次只和一个人互动 + 同一对角色之间的互动冷却
--
-- 背景（实测数据）：下午 3 小时的运行里，爱丽丝 / 特蕾莎 / 伊露雅三个人反复互相触发，
--   一小时内诞生了「特蕾莎 → 爱丽丝 → 伊露雅 → 爱丽丝 → 特蕾莎 → 爱丽丝」这种链条：
--     · 一行 companions 写着两个人，而系统一轮只能回应一个人，另一个要等后面几轮被补上，
--       于是叙述前后矛盾（一边说"带两人去了酒馆"，另一边说自己还在广场喷泉旁）；
--     · 每 20 分钟扫描一轮就再缠一次，二级地点在"酒馆 / 商会二楼 / 香料摊位 / 仓库"之间乱跳；
--     · 回应者的时间跨度（75 分钟）还大于触发者（45 分钟），时间线对不上。
--
-- 本版本配套的规则（代码已实现）：
--   2. 一次互动最多只保留一个对手（companions 超过 1 个时只留第一个）；
--   3. 同一对角色之间的互动冷却（本配置）：默认 4 小时，其间不再互相触发回应；
--   4. 回应回合强制沿用触发者的地点（一级 + 二级），不允许 AI 另写地方；
--   5. 回应回合的时间跨度不超过触发者，保证两人的这一步落在同一段时间里。
-- ============================================================

INSERT IGNORE INTO `sys_config` (`config_key`, `config_value`, `remark`) VALUES
    ('sandbox_interaction_cooldown_hours', '4',
     '沙盒同一对角色之间的互动冷却（小时）：默认 4，期间内两人不会再互相触发回应；填 0 表示不限制');
