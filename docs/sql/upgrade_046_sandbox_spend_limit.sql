-- 046 沙盒花费上限（让"花钱"有依据、有上限）
--
-- 背景：AI 会在 coins_change 里随手写一笔负数——实测「希露媞雅」第一次行动就写了 -15，
--   而 actions 里只是「在商队的货摊前购买了野浆果与火把」，明显不值 15 金币。
--   服务端过去只校验"不超过余额"，于是平白扣掉一大笔钱。
--
-- 现在的规则（代码里已实现）：
--   1. 单次行动的**非集市花费**按「余额分档 + 后台配置上限」取较小值：
--        余额 < 20  → 最多 5 金币
--        20 ~ 49    → 最多 8 金币
--        ≥ 50       → 最多等于本配置项
--      超出的部分会被截断，并在金币流水里注明「原花费 X 金币，已按单次上限 Y 截断」；
--   2. 旅人集市的购买走 shop_buy（真实标价、真实库存），不占用这个额度；
--   3. 提示词里同时给了常见消费参考价（一顿饭 1~3、住宿 2~5、短途车马 2~6、长途 8~20…），
--      并强调「集市买的东西不要再算进 coins_change」，避免同一笔钱被扣两次。
-- ============================================================

INSERT IGNORE INTO `sys_config` (`config_key`, `config_value`, `remark`) VALUES
    ('sandbox_max_spend_per_act', '10', '沙盒角色单次行动的「非集市花费」上限（金币）：余额越少越省，超出会被截断并在流水里注明');
