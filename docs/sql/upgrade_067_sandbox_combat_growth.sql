-- ============================================================
-- 067 沙盒：战斗力成长（完成委托按类型×难度 + 闲置修炼）
--
-- 背景：角色战斗力几乎从不变。
--   实测本地 178 条行动里只有 1 条 combat_change ≠ 0，其中「完成委托」的 10 步全是 0。
--   原因有二：
--     ① 提示词只在「奖励里有更好的装备、或讨伐了对手」时才允许 +1~+3，采集/护送/跑腿类天然落空；
--     ② 战斗力拆成「自身实力 + 装备加成」之后，AI 的"变强"全走了装备，自身实力一直不动。
--   现在改成：完成委托那一步必须显式判断一次战斗力，并按「类型 × 难度」的区间夹上限；
--   另外空闲时「想变强」的角色可以主动修炼。
--
-- 一、sandbox_quest_combat_gain
--   完成委托允许的战力成长表，格式 `类型:难度1,难度2,难度3,难度4,难度5`，多类型用 | 分隔，
--   每档可写单值 2 或区间 1-3。默认：
--     hunt:0-1,0-1,0-2,1-3,1-3    讨伐（真正动过手才涨）
--     explore:0,0-1,0-2,0-2,1-3   探索
--     escort:0,0,0-1,0-1,0-2      护送
--     gather:0,0,0,0,0-1          采集（搬运采药不会让人更能打）
--     chore:0,0,0,0,0             杂活
--   语义是**上限不是保底**：AI 判断没长进就填 0；给多了服务端截到上限。
--   类型没写进表里的按 0 处理（以后新加的类型不会悄悄通胀，也不会抹平人物实力差距）。
--
-- 二、sandbox_idle_train_gain_max
--   和委托无关：角色手头没委托、状态还行时主动修炼/切磋/琢磨魔法，单次允许涨多少自身实力（默认 2）。
--   提示词里只有「实力观」偏向渴望变强的角色才会被鼓励这么做，且要求写清代价、不要连续多步修炼。
--
-- 脚本幂等，可重复执行。
-- ============================================================

